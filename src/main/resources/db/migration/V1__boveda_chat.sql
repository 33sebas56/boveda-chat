create table app_users (
  id uuid primary key,
  username varchar(24) not null unique,
  display_name varchar(60) not null,
  password_hash varchar(100) not null,
  phone varchar(16) unique,
  phone_verified boolean not null default false,
  enabled boolean not null default true,
  role varchar(10) not null,
  created_at timestamp with time zone not null
);
create table conversations (
  id uuid primary key,
  user_low_id uuid not null references app_users(id),
  user_high_id uuid not null references app_users(id),
  low_read_id bigint not null default 0,
  high_read_id bigint not null default 0,
  updated_at timestamp with time zone not null,
  constraint different_users check (user_low_id <> user_high_id),
  constraint unique_pair unique (user_low_id, user_high_id)
);
create index conversation_low on conversations(user_low_id, updated_at);
create index conversation_high on conversations(user_high_id, updated_at);
create table stored_files (
  id uuid primary key,
  owner_id uuid not null references app_users(id),
  original_name varchar(180) not null,
  mime varchar(80) not null,
  size_bytes bigint not null,
  sha256 varchar(64) not null,
  object_key varchar(80) not null unique,
  revoked boolean not null default false,
  created_at timestamp with time zone not null
);
create index file_owner on stored_files(owner_id, created_at);
create table chat_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references conversations(id),
  sender_id uuid not null references app_users(id),
  ciphertext text,
  attachment_id uuid references stored_files(id),
  created_at timestamp with time zone not null,
  constraint message_has_content check (ciphertext is not null or attachment_id is not null)
);
create index message_conversation on chat_messages(conversation_id, id);
create index message_file on chat_messages(attachment_id);
create table audit_events (
  id bigint generated by default as identity primary key,
  actor varchar(100) not null,
  action varchar(40) not null,
  detail varchar(240) not null,
  created_at timestamp with time zone not null
);
create index audit_date on audit_events(created_at);
create index audit_action_date on audit_events(action, created_at);
